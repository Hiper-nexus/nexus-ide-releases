import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const rootDir = path.resolve(__dirname, '..');
const srcDir = path.join(rootDir, 'assets', 'skills', 'impeccable');
const outFile = path.join(rootDir, 'src', 'main', 'orch', 'impeccable-manifest.ts');

function walk(dir) {
  const files = [];
  const list = fs.readdirSync(dir, { withFileTypes: true });
  for (const entry of list) {
    const res = path.resolve(dir, entry.name);
    if (entry.isDirectory()) {
      files.push(...walk(res));
    } else {
      files.push(res);
    }
  }
  return files;
}

if (!fs.existsSync(srcDir)) {
  console.error(`Source directory does not exist: ${srcDir}`);
  process.exit(1);
}

const allFiles = walk(srcDir);
const manifest = {};

for (const file of allFiles) {
  const relPath = path.relative(srcDir, file);
  if (relPath.includes('.DS_Store')) continue;

  const buffer = fs.readFileSync(file);
  // Heuristic: check for null bytes or check extension
  const isBinary = relPath.endsWith('.png') || relPath.endsWith('.jpg') || relPath.endsWith('.pdf') || buffer.includes(0);

  manifest[relPath] = {
    content: buffer.toString(isBinary ? 'base64' : 'utf8'),
    encoding: isBinary ? 'base64' : 'utf8',
  };
}

const tsContent = `// Auto-generated by scripts/bundle-impeccable.mjs. Do not edit manually.
export interface ImpeccableAsset {
  content: string;
  encoding: 'utf8' | 'base64';
}

export const IMPECCABLE_MANIFEST: Record<string, ImpeccableAsset> = ${JSON.stringify(manifest, null, 2)};
`;

fs.writeFileSync(outFile, tsContent, 'utf8');
console.log(`Successfully bundled ${Object.keys(manifest).length} Impeccable files to ${outFile}`);
