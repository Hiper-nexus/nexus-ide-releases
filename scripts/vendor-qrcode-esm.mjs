#!/usr/bin/env node
/**
 * Regenera src/vendor/qrcode/bundle.mjs a partir dos fontes CJS vendored
 * (node-qrcode + dijkstrajs, ambos MIT).
 *
 * Por que existe: o dev server do Vite serve os arquivos de src/ como ESM
 * cru — o core CJS do node-qrcode (`require`/`exports.*`) explodia com
 * "require is not defined" em cache frio e o renderer inteiro não montava.
 * O build de produção (rollup commonjs) tolerava, então o bug só aparecia
 * no dev. O bundle ESM gerado aqui funciona igual nos dois mundos.
 *
 * Rode após atualizar o vendor: `node scripts/vendor-qrcode-esm.mjs`
 * Nota: usa o esbuild hoisted do vite (sem devDependency própria). Se o
 * vite mudar de major, regenere e revise o diff do bundle.
 */
import { build } from 'esbuild';

const HEADER = `/**
 * GENERATED by scripts/vendor-qrcode-esm.mjs — não editar à mão.
 * Fontes: src/vendor/qrcode/core/ + renderer/ (node-qrcode, MIT) e
 * dijkstrajs.js (MIT). Licenças: ./LICENSE-node-qrcode, ./LICENSE-dijkstrajs.
 */`;

await build({
  entryPoints: ['src/vendor/qrcode/esm-entry.js'],
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  target: 'es2020',
  outfile: 'src/vendor/qrcode/bundle.mjs',
  banner: { js: HEADER },
  logLevel: 'info',
});
console.log('bundle.mjs regenerado');
