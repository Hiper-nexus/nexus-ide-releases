import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, '..');

/**
 * Bundled builtin skills: assets/skills/<dir> → módulo TS com o manifesto
 * (o skill-mirror materializa no spawn de cada agente). Para adicionar uma
 * skill embutida nova: vendorar em assets/skills/, registrar aqui e
 * materializar no skill-mirror.
 */
const SKILLS = [
  {
    dir: 'impeccable',
    constName: 'IMPECCABLE_MANIFEST',
    outFile: 'impeccable-manifest.ts',
  },
  {
    dir: 'archify',
    constName: 'ARCHIFY_MANIFEST',
    outFile: 'archify-manifest.ts',
  },
  {
    dir: 'bmad-templates',
    constName: 'BMAD_TEMPLATES_MANIFEST',
    outFile: 'bmad-templates-manifest.ts',
  },
  {
    dir: 'superpowers',
    constName: 'SUPERPOWERS_MANIFEST',
    outFile: 'superpowers-manifest.ts',
  },
  {
    dir: 'dembrandt',
    constName: 'DEMBRANDT_MANIFEST',
    outFile: 'dembrandt-manifest.ts',
  },
];

function walk(dir) {
  const files = [];
  const entries = fs
    .readdirSync(dir, { withFileTypes: true })
    .sort((left, right) => left.name < right.name ? -1 : left.name > right.name ? 1 : 0);
  for (const entry of entries) {
    const res = path.resolve(dir, entry.name);
    if (entry.isDirectory()) files.push(...walk(res));
    else files.push(res);
  }
  return files;
}

for (const skill of SKILLS) {
  const srcDir = path.join(rootDir, 'assets', 'skills', skill.dir);
  const outFile = path.join(rootDir, 'src', 'main', 'orch', skill.outFile);
  if (!fs.existsSync(srcDir)) {
    console.error(`Source directory does not exist: ${srcDir}`);
    process.exit(1);
  }

  const manifest = {};
  for (const file of walk(srcDir)) {
    // POSIX separators in the manifest keys: they are generated on one
    // platform and consumed on every other, and the materializer resolves them
    // through path.join (which accepts '/' on Windows too).
    const relPath = path.relative(srcDir, file).split(path.sep).join('/');
    if (relPath.includes('.DS_Store')) continue;
    const buffer = fs.readFileSync(file);
    // A file is safe as utf8 only if decode+re-encode is byte-for-byte
    // lossless; anything else (any binary, regardless of extension) is stored
    // as base64 so the round-trip can never corrupt it.
    const isBinary = !Buffer.from(buffer.toString('utf8'), 'utf8').equals(buffer);
    // Keep generated manifests byte-stable across POSIX and Windows checkouts.
    // Git may materialize vendored text with CRLF on Windows; the runtime
    // payload must retain the canonical LF form used by the release tree.
    const content = isBinary
      ? buffer.toString('base64')
      : buffer.toString('utf8').replace(/\r\n?/gu, '\n');
    // The exec bit is part of the payload for vendored CLIs (impeccable ships
    // `scripts/impeccable` + a Mach-O launcher). Only the bit is stored, not
    // the mode: POSIX modes do not round-trip through Windows and nothing else
    // about the mode matters to the materializer.
    const isExecutable =
      (fs.statSync(file).mode & 0o111) !== 0 ||
      relPath === 'scripts/impeccable' ||
      // Git's executable bit is not preserved by a Windows checkout. The
      // vendored platform payloads under these directories are executable
      // even when their mode is reported as 0644 on NTFS.
      /(^|\/)(?:bin|scripts\/bin)\//u.test(relPath);
    manifest[relPath] = {
      content,
      encoding: isBinary ? 'base64' : 'utf8',
      ...(isExecutable ? { executable: true } : {}),
    };
  }

  const tsContent = `// Auto-generated by scripts/bundle-skills.mjs. Do not edit manually.
export interface SkillAsset {
  content: string;
  encoding: 'utf8' | 'base64';
  /** Vendored executables (e.g. the impeccable CLI) must land runnable. */
  executable?: boolean;
}

export const ${skill.constName}: Record<string, SkillAsset> = ${JSON.stringify(manifest, null, 2)};
`;

  fs.writeFileSync(outFile, tsContent, 'utf8');
  console.log(
    `Bundled ${Object.keys(manifest).length} files: assets/skills/${skill.dir} → ${path.relative(rootDir, outFile)}`,
  );
}
