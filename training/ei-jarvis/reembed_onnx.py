#!/usr/bin/env python3
"""
Copia um ONNX de wake PT-BR para o Nexus e regenera o módulo base64 embutido.

Uso:
  python3 reembed_onnx.py path/to/ei_jarvis.onnx
  python3 reembed_onnx.py path/to/model.onnx --also-user-override
"""

from __future__ import annotations

import argparse
import base64
import hashlib
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]  # nexus-ide/
RESOURCES = ROOT / "resources" / "wake" / "ei-jarvis-ptbr.onnx"
TS_OUT = ROOT / "src" / "main" / "voice" / "wake-models-ptbr.ts"
USER_OVERRIDE = Path.home() / ".nexus" / "models" / "wake" / "custom.onnx"


def main() -> int:
    parser = argparse.ArgumentParser(description="Re-embute ONNX wake PT-BR no Nexus")
    parser.add_argument("onnx", type=Path, help="Caminho do .onnx exportado")
    parser.add_argument(
        "--also-user-override",
        action="store_true",
        help=f"Também copia para {USER_OVERRIDE}",
    )
    args = parser.parse_args()

    src: Path = args.onnx.expanduser().resolve()
    if not src.is_file():
        print(f"erro: arquivo não encontrado: {src}", file=sys.stderr)
        return 1
    raw = src.read_bytes()
    if len(raw) < 1024:
        print(f"erro: ONNX muito pequeno ({len(raw)} bytes)", file=sys.stderr)
        return 1
    if raw[0] != 0x08:
        print(
            "erro: cabeçalho não parece ModelProto ONNX (esperado byte 0x08)",
            file=sys.stderr,
        )
        return 1

    sha = hashlib.sha256(raw).hexdigest()
    b64 = base64.b64encode(raw).decode("ascii")

    RESOURCES.parent.mkdir(parents=True, exist_ok=True)
    RESOURCES.write_bytes(raw)

    TS_OUT.write_text(
        "/**\n"
        " * Bundled PT-BR wake head (\"Ei Jarvis\" / \"Jarvis\").\n"
        " * Generated by training/ei-jarvis/reembed_onnx.py — do not edit by hand.\n"
        " * Trained via LiveKit WakeWord (or train_local.py). Ships with every\n"
        " * NexusIDE build (macOS / Windows / Linux).\n"
        f" * SHA-256: {sha}\n"
        f" * Size: {len(raw)} bytes\n"
        " * Source: "
        f"{src.name}\n"
        " */\n"
        f"export const EI_JARVIS_PTBR_ONNX_SHA256 = '{sha}';\n"
        f"export const EI_JARVIS_PTBR_ONNX_BYTES = {len(raw)};\n"
        f"export const EI_JARVIS_PTBR_ONNX_B64 =\n  '{b64}';\n",
        encoding="utf-8",
    )

    if args.also_user_override:
        USER_OVERRIDE.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(src, USER_OVERRIDE)
        print(f"override local: {USER_OVERRIDE}")

    print(f"resource:  {RESOURCES} ({len(raw)} bytes)")
    print(f"embedded:  {TS_OUT} ({TS_OUT.stat().st_size} bytes)")
    print(f"sha256:    {sha}")
    print("OK — reinicie o NexusIDE para carregar o head PT-BR.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
