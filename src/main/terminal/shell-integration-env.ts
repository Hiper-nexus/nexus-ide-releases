/**
 * Env injection for OSC 133 shell integration when CommandBlocks flag is ON.
 *
 * Does NOT write into the PTY stream (that pollutes history and races user input).
 * Uses ZDOTDIR (zsh) / bash --rcfile-style ENV hooks via managed temp rc files
 * that source the user rc first, then the Nexus OSC 133 script.
 */
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { FEATURE_FLAG_IDS } from '../../shared/feature-flags';
import { getFeatureFlagRegistry } from '../feature-flags/feature-flag-registry';

export function isShellIntegrationEnabled(): boolean {
  return getFeatureFlagRegistry().isEnabled(
    FEATURE_FLAG_IDS.terminalCommandBlocks,
  );
}

/** Resolve packaged/dev path to resources/shell-integration/. */
export function resolveShellIntegrationDir(): string | null {
  const candidates: string[] = [];
  const resourcesPath = (process as NodeJS.Process & { resourcesPath?: string })
    .resourcesPath;
  if (resourcesPath) {
    candidates.push(path.join(resourcesPath, 'shell-integration'));
  }
  if (process.env.NEXUS_RESOURCES_DIR) {
    candidates.push(
      path.join(process.env.NEXUS_RESOURCES_DIR, 'shell-integration'),
    );
  }
  candidates.push(path.join(process.cwd(), 'resources', 'shell-integration'));
  for (const dir of candidates) {
    if (dir && fs.existsSync(path.join(dir, 'nexus-osc133.zsh'))) {
      return dir;
    }
  }
  return null;
}

function shellQuote(value: string): string {
  return `'${value.replace(/'/g, `'\\''`)}'`;
}

function shellBase(shellPath: string): string {
  return path.basename(shellPath).toLowerCase();
}

export interface ShellIntegrationApplyResult {
  readonly env: Record<string, string>;
  /** Temp dirs created for ZDOTDIR / bashrc — delete on session exit. */
  readonly cleanupPaths: readonly string[];
}

/**
 * Merge NEXUS_SHELL_INTEGRATION + shell-specific auto-load into child env.
 * Safe no-op when flag off.
 */
export function applyShellIntegrationEnv(
  env: Record<string, string>,
  shellPath: string,
): ShellIntegrationApplyResult {
  if (!isShellIntegrationEnabled()) {
    return { env, cleanupPaths: [] };
  }

  const dir = resolveShellIntegrationDir();
  const next: Record<string, string> = {
    ...env,
    NEXUS_SHELL_INTEGRATION: '1',
  };
  const cleanupPaths: string[] = [];
  if (!dir) {
    return { env: next, cleanupPaths };
  }

  const base = shellBase(shellPath);
  try {
    if (base.includes('zsh')) {
      const script = path.join(dir, 'nexus-osc133.zsh');
      const zdot = fs.mkdtempSync(path.join(os.tmpdir(), 'nexus-zdot-'));
      cleanupPaths.push(zdot);
      const userZdot = env.ZDOTDIR || os.homedir();
      const userRc = path.join(userZdot, '.zshrc');

      // Managed ZDOTDIR: load user rc (if any) then OSC 133, then restore user ZDOTDIR.
      const zshrcBody = [
        '# Generated by Nexus IDE — shell integration (do not edit)',
        `[[ -f ${shellQuote(userRc)} ]] && source ${shellQuote(userRc)}`,
        `[[ -f ${shellQuote(script)} ]] && source ${shellQuote(script)}`,
        '[[ -n "$__NX_ORIG_ZDOTDIR" ]] && export ZDOTDIR="$__NX_ORIG_ZDOTDIR" || unset ZDOTDIR',
        '',
      ].join('\n');
      fs.writeFileSync(path.join(zdot, '.zshrc'), zshrcBody, { mode: 0o600 });

      // Managed .zprofile for login shells: source /etc/zprofile (macOS path_helper) then user's .zprofile
      const zprofileBody = [
        '# Generated by Nexus IDE — login profile loader (do not edit)',
        'USER_ZDOTDIR="${__NX_ORIG_ZDOTDIR:-$HOME}"',
        'if [[ -z "$__NX_ETC_ZPROFILE_SOURCED" && -f "/etc/zprofile" ]]; then',
        '  export __NX_ETC_ZPROFILE_SOURCED=1',
        '  source "/etc/zprofile"',
        'fi',
        'if [[ -z "$NEXUS_FAST_SHELL" && -f "$USER_ZDOTDIR/.zprofile" ]]; then',
        '  source "$USER_ZDOTDIR/.zprofile"',
        'fi',
        '',
      ].join('\n');
      fs.writeFileSync(path.join(zdot, '.zprofile'), zprofileBody, { mode: 0o600 });

      // Managed .zshenv: source user's .zshenv if present, then preserve managed ZDOTDIR
      const zshenvBody = [
        '# Generated by Nexus IDE — environment loader (do not edit)',
        '__NX_MANAGED_ZDOTDIR="$ZDOTDIR"',
        'USER_ZDOTDIR="${__NX_ORIG_ZDOTDIR:-$HOME}"',
        'if [[ -f "$USER_ZDOTDIR/.zshenv" ]]; then',
        '  source "$USER_ZDOTDIR/.zshenv"',
        'fi',
        'export ZDOTDIR="$__NX_MANAGED_ZDOTDIR"',
        '',
      ].join('\n');
      fs.writeFileSync(path.join(zdot, '.zshenv'), zshenvBody, { mode: 0o600 });

      next.ZDOTDIR = zdot;
      next.__NX_ORIG_ZDOTDIR = userZdot;
      next.NEXUS_OSC133_ZSH = script;
    } else if (base.includes('bash')) {
      const script = path.join(dir, 'nexus-osc133.bash');
      // Interactive bash does not load BASH_ENV. Provide a composite rc via
      // NEXUS_BASHRC and spawn args (see shellIntegrationSpawnArgs).
      const rcDir = fs.mkdtempSync(path.join(os.tmpdir(), 'nexus-bashrc-'));
      cleanupPaths.push(rcDir);
      const composite = path.join(rcDir, 'bashrc');
      const userBashrc = path.join(os.homedir(), '.bashrc');
      const body = [
        '# Generated by Nexus IDE — shell integration (do not edit)',
        `[[ -f ${shellQuote(userBashrc)} ]] && source ${shellQuote(userBashrc)}`,
        `[[ -f ${shellQuote(script)} ]] && source ${shellQuote(script)}`,
        '',
      ].join('\n');
      fs.writeFileSync(composite, body, { mode: 0o600 });
      next.NEXUS_OSC133_BASH = script;
      next.NEXUS_BASHRC = composite;
    } else if (base.includes('fish')) {
      next.NEXUS_OSC133_FISH = path.join(dir, 'nexus-osc133.fish');
      // Fish: user must source from config.fish; env marker only (no safe auto).
    }
  } catch {
    // Fail open for shell usability — integration is best-effort.
  }

  return { env: next, cleanupPaths };
}

/**
 * Extra argv so interactive bash loads the composite rc without PTY writes.
 * zsh uses ZDOTDIR only (no extra args).
 */
export function shellIntegrationSpawnArgs(shellPath: string, env: Record<string, string>): string[] {
  if (!isShellIntegrationEnabled()) return [];
  const base = shellBase(shellPath);
  if (base.includes('bash') && env.NEXUS_BASHRC) {
    // --rcfile replaces system bashrc chain; composite already sources ~/.bashrc.
    return ['--rcfile', env.NEXUS_BASHRC];
  }
  return [];
}

/** @deprecated Prefer applyShellIntegrationEnv — never write source into PTY. */
export function shellIntegrationBootstrapCommand(_shellPath: string): string | null {
  return null;
}

export function cleanupShellIntegrationPaths(paths: readonly string[]): void {
  for (const p of paths) {
    try {
      fs.rmSync(p, { recursive: true, force: true });
    } catch {
      /* best-effort */
    }
  }
}
