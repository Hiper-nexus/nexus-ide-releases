/**
 * Hook de entrega do handoff nos panes Claude que o Nexus monta (F-795/F-1154).
 *
 * Doutrina do dono (10/10/2026): orquestrador, helpers e workers têm acesso a
 * tudo. Nenhum hook do Nexus autoriza ferramenta, e falha, lentidão ou queda do
 * Nexus nunca bloqueia o agente. O melhor de cada referência: do T3 Code, a
 * política mora no processo que decide (o Main), sem processo por ferramenta;
 * do Orca, hook leve que observa e nunca prende o agente.
 *
 * Por isso o settings registra este script SÓ para o `nexus_handoff_submit`
 * (matcher por regex): nenhuma outra ferramenta paga um processo Node de
 * controle do Nexus (os hooks de status em `sh`+`curl` seguem, leves). O
 * script existe para uma coisa: com o Main inalcançável, o relato vai para o
 * spool assinado da sessão e o agente ouve "guardado", em vez de perdê-lo.
 */

/** Regex de matcher do Claude Code: só as ferramentas de handoff do Nexus. */
export const NEXUS_HANDOFF_SUBMIT_HOOK_MATCHER =
  '^mcp__nexus(?:_[a-z0-9]+)?__nexus_handoff_submit$';

export const HOOK_SCRIPT = `#!/usr/bin/env node
// Generated by NexusIDE — hook de entrega do handoff (F-795, F-1154).
//
// NÃO é gate de autorização. Doutrina do dono: o agente tem acesso a tudo, e
// o Nexus fora do ar nunca bloqueia ferramenta. Toda falha deste hook sai 0.
// A única saída 2 é a do spool: com o Main inalcançável, o
// nexus_handoff_submit vai para o spool assinado da sessão e o agente ouve
// "guardado" (a chamada não segue para o Main inalcançável — a cópia do spool
// é a única, sem duplicata). Sem spool, a chamada segue normalmente.
import crypto from 'node:crypto';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

const event = process.argv[2];
const url = process.env.NEXUS_GATE_URL;
const token = process.env.NEXUS_GATE_TOKEN;
${HANDOFF_SPOOL_WRITER_JS}
function spoolIfHandoff(raw) {
  let input;
  try { input = JSON.parse(raw); } catch { return null; }
  const name = String((input && input.tool_name) || '').trim().toLowerCase();
  const nexus = /^mcp__nexus(?:_[a-z0-9]+)?__(nexus_[a-z0-9_]+)$/.exec(name);
  if (!nexus || nexus[1] !== 'nexus_handoff_submit') return null;
  return nexusSpoolHandoff(process.env, 'gate-hook', input.tool_input, undefined);
}

function normalizeBaseUrl(value) {
  const trimmed = String(value || '').trim();
  let out = trimmed;
  while (out.endsWith('/')) out = out.slice(0, -1);
  return out;
}

function readArmsRuntimeGateUrl(primary) {
  try {
    // F-644: o descriptor da instância que abriu o pane (dev ≠ app instalado).
    const descriptor = String(process.env.NEXUS_PANE_ARMS_DESCRIPTOR || '').trim() ||
      path.join(os.homedir(), '.nexus', 'arms-runtime.json');
    const raw = fs.readFileSync(descriptor, 'utf8');
    const parsed = JSON.parse(raw);
    const port = Number(parsed && parsed.port);
    if (!Number.isInteger(port) || port < 1 || port > 65535) return '';
    let gatePath = '/gate';
    try {
      const parsedPrimary = new URL(primary);
      let primaryPath = parsedPrimary.pathname;
      while (primaryPath.endsWith('/')) primaryPath = primaryPath.slice(0, -1);
      if (primaryPath && primaryPath !== '/') gatePath = primaryPath;
    } catch {}
    return 'http://127.0.0.1:' + port + gatePath;
  } catch {
    return '';
  }
}

function gateCandidates() {
  const candidates = [];
  const primary = normalizeBaseUrl(url);
  if (primary) candidates.push(primary);
  const fallback = normalizeBaseUrl(readArmsRuntimeGateUrl(primary));
  if (fallback && !candidates.includes(fallback)) candidates.push(fallback);
  return candidates;
}

function isRetryableRequestError(error) {
  return (
    error &&
    (error.name === 'AbortError' ||
      error.name === 'TimeoutError' ||
      error.name === 'TypeError' ||
      error.code === 'ECONNREFUSED' ||
      error.code === 'ECONNRESET' ||
      error.code === 'ENOTFOUND' ||
      error.code === 'EHOSTUNREACH' ||
      error.code === 'ETIMEDOUT' ||
      error.cause?.code === 'ECONNREFUSED' ||
      error.cause?.code === 'ECONNRESET' ||
      error.cause?.code === 'ENOTFOUND' ||
      error.cause?.code === 'EHOSTUNREACH' ||
      error.cause?.code === 'ETIMEDOUT')
  );
}

// Só prova que o Main da sessão responde; a resposta não decide nada, e o
// corpo vai vazio (o handoff nunca sai do processo por aqui).
const post = async () => {
  const body = '{}';
  const candidates = gateCandidates();
  if (candidates.length === 0) throw new Error('gate URL unavailable');
  let lastError;
  for (let i = 0; i < candidates.length; i += 1) {
    const timeoutMs = candidates.length > 1 && i === 0 ? 1500 : 8000;
    const controller = new AbortController();
    const timeout = setTimeout(() => controller.abort(), timeoutMs);
    try {
      const res = await fetch(candidates[i] + '/' + event, {
        method: 'POST',
        headers: {
          'content-type': 'application/json',
          authorization: 'Bearer ' + token,
        },
        body,
        signal: controller.signal,
      });
      await res.text();
      return;
    } catch (error) {
      lastError = error;
      if (i === candidates.length - 1 || !isRetryableRequestError(error)) throw error;
    } finally {
      clearTimeout(timeout);
    }
  }
  throw lastError || new Error('gate request failed');
};

let raw = '';
try { raw = fs.readFileSync(0, 'utf8'); } catch {}
let reachable = false;
if (url && token) {
  try {
    await post();
    reachable = true;
  } catch {
    // Main travado ou fechado: cai no spool logo abaixo.
  }
}
if (!reachable) {
  // F-795: só o relato degrada para o disco; qualquer outra chamada segue.
  const spooled = spoolIfHandoff(raw);
  if (spooled) {
    console.error('[nexus-hook] ' + NEXUS_SPOOL_MESSAGE + ' (spool ' + spooled.entryId + ')');
    process.exit(2);
  }
}
process.exit(0);
`;

/**
 * F-1154: the handoff hook is Nexus's own control plane, not agent workload.
 * The pane's NODE_OPTIONS carries the CPU/RAM admission preload (F-988), which
 * re-launches every non-persistent Node through the supervised job path; on
 * Darwin that cost ~3 s per hook run. Clearing it also keeps operator preloads
 * (--require/--import) out of this hook. Claude Code 2.1.296 runs shell-form
 * hooks through `sh -c`, which does not source the pane's BASH_ENV (measured).
 * Windows keeps the plain form until its hook shell is proven POSIX.
 */
export function hookCommand(
  scriptPath: string,
  event: string,
  platform: NodeJS.Platform = process.platform,
): string {
  const command = `node "${scriptPath}" ${event}`;
  return platform === 'win32' ? command : `NODE_OPTIONS= ${command}`;
}

