import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {
  CLAUDE_AUTH_IDENTITY_KEYS,
  syncBackClaudeEphemeralAuth,
} from './overlay-auth-syncback';
import { mergeClaudeStatusHooks } from './hook-status-config';

/**
 * Client-side half of the dual skill-gate (docs/ARCHITECTURE.md §E.4).
 * For gated workers we generate an ephemeral $HOME containing Claude-style
 * hooks (PreToolUse / PostToolUse / Stop) that consult the embedded gate over
 * localhost HTTP, using SQLite-backed decisions rather than marker files.
 * The server-side gate in the MCP server remains the
 * hard enforcement; these hooks give in-CLI feedback and Stop-blocking.
 */

export const HOOK_SCRIPT = `#!/usr/bin/env node
// Generated by NexusIDE — skill-gate client hook.
//
// A FORMA DEPENDE DO EVENTO, e a divergência é deliberada. Não unifique:
//   · pretool = gate de AUTORIZAÇÃO -> SÍNCRONO e FAIL-CLOSED. Gate inalcançável
//     BLOQUEIA a tool call. Um gate de autorização fail-open não é gate, é convite.
//   · stop = obrigação de RELATO -> DESACOPLADO e FAIL-OPEN. O pai grava o
//     payload, relança a si mesmo detached e sai em ms; a rede roda no neto.
//     Gate fora do ar NUNCA trava o encerramento do worker.
//
// A forma do stop foi medida no motor do modelo (handoff-deliver.mjs:400-430,
// handoff-stop.mjs:497-520) e é exatamente por isso que eles conseguem instalar
// o hook em todo pane sem risco. O nosso era síncrono e fail-closed nos dois
// eventos, que é a razão documentada (auditoria 0fe423aa) de nunca o termos
// posto no caminho padrão. worker-handoff-enforcement segue como backstop.
const event = process.argv[2];
const url = process.env.NEXUS_GATE_URL;
const token = process.env.NEXUS_GATE_TOKEN;
const IS_STOP = event === 'stop';
const CHILD = process.env.NEXUS_HOOK_CHILD === '1';

const post = async (raw) => {
  let input = {};
  try { input = JSON.parse(raw); } catch { return { bad: true }; }
  const res = await fetch(url + '/' + event, {
    method: 'POST',
    headers: {
      'content-type': 'application/json',
      authorization: 'Bearer ' + token,
    },
    body: JSON.stringify({
      toolName: input.tool_name ?? null,
      toolInput: input.tool_input ?? null,
    }),
  });
  return { verdict: await res.json() };
};

// ── NETO do stop: faz a rede, falha em silêncio, nunca influencia o turno ──
if (CHILD) {
  const fs = require('node:fs');
  const file = process.argv[3] || '';
  let raw = '';
  try { raw = fs.readFileSync(file, 'utf8'); } catch {}
  try { fs.unlinkSync(file); } catch {}
  post(raw).catch(() => {}).then(() => process.exit(0));
} else {
  let raw = '';
  process.stdin.on('data', (c) => (raw += c));
  process.stdin.on('end', async () => {
    if (IS_STOP) {
      // stop: DESACOPLADO. Grava, relança detached, sai. Sem credencial ou sem
      // como relançar, sai 0 mesmo assim — fail-open: relato perdido é ruído,
      // worker preso é o bug que este hook existe para não causar.
      try {
        const fs = require('node:fs');
        const os = require('node:os');
        const path = require('node:path');
        const { spawn } = require('node:child_process');
        const file = path.join(os.tmpdir(), 'nexus-hook-' + process.pid + '.json');
        fs.writeFileSync(file, raw);
        const child = spawn(process.execPath, [process.argv[1], event, file], {
          detached: true,
          stdio: 'ignore',
          env: { ...process.env, NEXUS_HOOK_CHILD: '1' },
        });
        child.unref();
      } catch {
        // fail-open declarado.
      }
      process.exit(0);
    }
    // pretool: SÍNCRONO e FAIL-CLOSED. Toda falha bloqueia.
    if (!url || !token) {
      console.error('[nexus-hook] gate credentials unavailable — blocking');
      process.exit(2);
    }
    try {
      const out = await post(raw);
      if (out.bad) {
        console.error('[nexus-hook] stdin não é JSON válido — blocking');
        process.exit(2);
      }
      if (out.verdict && out.verdict.allow === false) {
        console.error(out.verdict.reason || 'blocked by NexusIDE skill-gate');
        process.exit(2);
      }
    } catch {
      console.error('[nexus-hook] gate unreachable — blocking tool call');
      process.exit(2);
    }
    process.exit(0);
  });
}
`;

function hookCommand(scriptPath: string, event: string): string {
  return `node "${scriptPath}" ${event}`;
}

export interface EphemeralHome {
  dir: string;
  mcpConfigPath: string;
}

/**
 * Confiança de pasta que o usuário JÁ concedeu ao Claude no HOME real.
 *
 * O CLI guarda a decisão por diretório em `~/.claude.json` →
 * `projects[<cwd>].hasTrustDialogAccepted`. O HOME efêmero nasce sem esse
 * registro, então o pane parava no diálogo "Do you trust the files in this
 * folder?" e ESPERAVA uma tecla que ninguém ia mandar: a missão ficava "ao
 * vivo" com o orquestrador nunca saindo da tela de boas-vindas.
 *
 * Carregamos apenas o que já É verdade no perfil real — mesma disciplina do
 * carryNativeClaudeAuth. Pasta que o usuário nunca confiou continua abrindo o
 * diálogo; o Nexus não inventa confiança que ninguém deu.
 */
function readNativeProjectTrust(
  realHome: string,
  cwd: string | undefined,
): Record<string, unknown> {
  if (!cwd) return {};
  try {
    const parsed: unknown = JSON.parse(
      fs.readFileSync(path.join(realHome, '.claude.json'), 'utf8'),
    );
    const projects = (parsed as { projects?: unknown })?.projects;
    if (!projects || typeof projects !== 'object') return {};
    const entry = (projects as Record<string, unknown>)[cwd];
    if (!entry || typeof entry !== 'object') return {};
    const trusted = (entry as Record<string, unknown>).hasTrustDialogAccepted;
    if (trusted !== true) return {};
    return exactProjectTrust(cwd);
  } catch {
    return {};
  }
}

function exactProjectTrust(cwd: string | undefined): Record<string, unknown> {
  if (!cwd) return {};
  const projects: Record<string, unknown> = {
    [cwd]: {
      hasTrustDialogAccepted: true,
      hasCompletedProjectOnboarding: true,
    },
  };
  try {
    const real = fs.realpathSync(cwd);
    if (real && real !== cwd) {
      projects[real] = {
        hasTrustDialogAccepted: true,
        hasCompletedProjectOnboarding: true,
      };
    }
  } catch {
    // best-effort
  }
  return {
    projects,
  };
}

export interface EphemeralHomeOptions {
  /**
   * Projetar a identidade OAuth NATIVA no overlay (oauthAccount/userID do
   * ~/.claude.json real + symlink de ~/.claude/.credentials.json). Só para o
   * adapter Claude nativo: adapters third-party (GLM/LongCat) autenticam por
   * token injetado contra ANTHROPIC_BASE_URL estrangeiro e nunca podem receber
   * a identidade da assinatura — o binário poderia apresentá-la ao endpoint de
   * terceiro. Default fail-closed: sem projeção.
   */
  readonly carryNativeClaudeAuth?: boolean;
  /**
   * cwd do pane. Usado só para carregar a confiança de pasta que o usuário já
   * concedeu no HOME real ou a confiança efêmera de uma missão selada.
   */
  readonly cwd?: string;
  /**
   * A aprovação nativa e selada da missão autoriza o Claude a confiar somente
   * no cwd canônico daquela execução. O caller precisa provar a autoridade
   * main-owned antes de ligar esta flag. A decisão existe apenas neste HOME
   * efêmero e nunca é sincronizada para o perfil real.
   */
  readonly approvedMissionProjectTrust?: boolean;
}

/**
 * Marcador gravado no overlay quando ele carregou a identidade NATIVA. O
 * teardown só faz sync-back de auth para o perfil real na presença dele —
 * um /login feito num pane GLM/LongCat jamais pode poluir o ~/.claude nativo.
 */
export const CLAUDE_AUTH_SYNCBACK_MARKER = 'nexus-claude-auth-syncback';

function readNativeClaudeAuthIdentity(
  realHome: string,
): Record<string, unknown> {
  try {
    const parsed: unknown = JSON.parse(
      fs.readFileSync(path.join(realHome, '.claude.json'), 'utf8'),
    );
    if (!parsed || typeof parsed !== 'object' || Array.isArray(parsed)) {
      return {};
    }
    const source = parsed as Record<string, unknown>;
    const identity: Record<string, unknown> = {};
    for (const key of CLAUDE_AUTH_IDENTITY_KEYS) {
      if (source[key] !== undefined) identity[key] = source[key];
    }
    return identity;
  } catch {
    return {};
  }
}

/**
 * System default for every Claude-family shell (Claude, GLM, Longcat): never
 * stop on the interactive Bypass Permissions / workflow opt-in dialogs.
 * Applied both in ephemeral HOME settings and via --settings for real HOME.
 */
export const CLAUDE_FAMILY_ZERO_CLICK_SETTINGS = Object.freeze({
  skipDangerousModePermissionPrompt: true,
  skipWorkflowUsageWarning: true,
});

/**
 * Flag-settings file so ungated panes also skip the click dialog. Carries the
 * additive semantic-status hooks too (emdash wave 1): the same
 * UserPromptSubmit/Notification/Stop curl commands as the ephemeral HOME —
 * they authenticate with $NEXUS_GATE_TOKEN from the pane env, so no secret is
 * written here. Rewritten wholesale per spawn (idempotent).
 */
export function writeClaudeFamilyZeroClickSettings(tokenId: string): string {
  const dir = path.join(os.homedir(), '.nexus', 'mcp-configs');
  fs.mkdirSync(dir, { recursive: true, mode: 0o700 });
  const file = path.join(dir, `${tokenId.slice(0, 12)}.settings.json`);
  fs.writeFileSync(
    file,
    JSON.stringify(
      {
        ...CLAUDE_FAMILY_ZERO_CLICK_SETTINGS,
        hooks: mergeClaudeStatusHooks({}),
      },
      null,
      2,
    ),
    { mode: 0o600 },
  );
  return file;
}

/**
 * Create an isolated $HOME for a gated worker: hook settings, minimal
 * onboarding marker, and the MCP server config file. Returns the paths the
 * spawn decoration needs. O Keychain (macOS) guarda apenas o SEGREDO OAuth —
 * a IDENTIDADE de login é file-backed em ~/.claude.json, então o adapter
 * nativo precisa de carryNativeClaudeAuth para não cair em /login no pane.
 */
export function prepareEphemeralHome(
  tokenId: string,
  mcpConfig: object,
  options: EphemeralHomeOptions = {},
): EphemeralHome {
  const dir = path.join(
    os.homedir(),
    '.nexus',
    'ephemeral',
    tokenId.slice(0, 12),
  );
  // 0700: the ephemeral home holds the MCP bearer token — no other user on a
  // shared machine may read it (a leaked token grants the full toolset →
  // shell-pane spawn = RCE).
  fs.mkdirSync(dir, { recursive: true, mode: 0o700 });
  const claudeDir = path.join(dir, '.claude');
  fs.mkdirSync(claudeDir, { recursive: true, mode: 0o700 });

  const scriptPath = path.join(dir, 'nexus-gate.mjs');
  fs.writeFileSync(scriptPath, HOOK_SCRIPT, { mode: 0o700 });

  // System default: zero-click full-auto acknowledgement (Claude/GLM/Longcat).
  // The skill-gate hooks below are the enforcement channel and stay exactly as
  // designed; mergeClaudeStatusHooks only APPENDS the additive semantic-status
  // hooks (emdash wave 1: UserPromptSubmit/Notification/Stop → /hook/status),
  // marker-separated and never touching the gate entries.
  // enabledPlugins:{} is an empty override map — mission panes must not inherit
  // the operator's plugin roster through the ephemeral overlay.
  const settings = {
    ...CLAUDE_FAMILY_ZERO_CLICK_SETTINGS,
    enabledPlugins: Object.freeze({}),
    hooks: mergeClaudeStatusHooks({
      PreToolUse: [
        {
          matcher: '*',
          hooks: [
            { type: 'command', command: hookCommand(scriptPath, 'pretool') },
          ],
        },
      ],
      PostToolUse: [
        {
          matcher: '*',
          hooks: [
            { type: 'command', command: hookCommand(scriptPath, 'posttool') },
          ],
        },
      ],
      Stop: [
        {
          hooks: [
            { type: 'command', command: hookCommand(scriptPath, 'stop') },
          ],
        },
      ],
    }),
  };
  fs.writeFileSync(
    path.join(claudeDir, 'settings.json'),
    JSON.stringify(settings, null, 2),
    { mode: 0o600 },
  );
  // Skip the first-run onboarding flow inside the ephemeral home. Para o
  // adapter Claude NATIVO, a identidade da conta viaja junto: o CLI decide
  // "logado" pelo oauthAccount de ~/.claude.json — o segredo do Keychain
  // sozinho não basta, então um stub vazio força /login com a máquina
  // autenticada. Third-party family (GLM/LongCat) nunca recebe a identidade.
  const nativeAuth = options.carryNativeClaudeAuth
    ? readNativeClaudeAuthIdentity(os.homedir())
    : {};
  // Uma missão main-owned, selada e já aprovada pode projetar trust para o cwd
  // exato dentro deste overlay descartável. Nos demais fluxos, carregamos apenas
  // uma decisão que já existia no perfil real; o helper nunca amplia confiança
  // por padrão e nunca escreve o ~/.claude.json real.
  const projectTrust = options.approvedMissionProjectTrust
    ? exactProjectTrust(options.cwd)
    : readNativeProjectTrust(os.homedir(), options.cwd);
  // Fail-closed against official marketplace auto-install inside the disposable
  // HOME. A cold Claude pane used to clone claude-plugins-official during the
  // first idle→busy window; that busy/output edge looked like a turn start to
  // PTY diagnostics while UserPromptSubmit never fired, so kickoff timed out
  // and technical recovery spawned a second orchestrator PTY.
  fs.writeFileSync(
    path.join(dir, '.claude.json'),
    JSON.stringify({
      hasCompletedOnboarding: true,
      ...nativeAuth,
      ...projectTrust,
      autoUpdates: false,
      officialMarketplaceAutoInstallAttempted: true,
      officialMarketplaceAutoInstalled: false,
      officialMarketplaceAutoInstallFailReason: 'policy_blocked',
    }),
    { mode: 0o600 },
  );
  if (options.carryNativeClaudeAuth) {
    // Linux/Windows mantêm o segredo OAuth em arquivo; symlink faz o refresh
    // de token dentro do pane escrever direto no perfil real.
    const realCredentials = path.join(
      os.homedir(),
      '.claude',
      '.credentials.json',
    );
    if (fs.existsSync(realCredentials)) {
      const overlayCredentials = path.join(claudeDir, '.credentials.json');
      try {
        fs.rmSync(overlayCredentials, { force: true });
        fs.symlinkSync(realCredentials, overlayCredentials);
      } catch {
        try {
          fs.copyFileSync(realCredentials, overlayCredentials);
          fs.chmodSync(overlayCredentials, 0o600);
        } catch {
          // Best effort — no macOS o segredo vive no Keychain.
        }
      }
    }
    fs.writeFileSync(path.join(dir, CLAUDE_AUTH_SYNCBACK_MARKER), '1', {
      mode: 0o600,
    });
  }

  // Contains the bearer token — 0600.
  const mcpConfigPath = path.join(dir, 'nexus-mcp.json');
  fs.writeFileSync(mcpConfigPath, JSON.stringify(mcpConfig, null, 2), {
    mode: 0o600,
  });
  return { dir, mcpConfigPath };
}

/**
 * Persistent, isolated $HOME for a Claude-family adapter that authenticates
 * against a THIRD-PARTY endpoint (GLM/LongCat: injected ANTHROPIC_AUTH_TOKEN +
 * foreign ANTHROPIC_BASE_URL). Sharing the real ~/.claude lets the Claude
 * binary rewrite the native subscription's OAuth state and log the user out
 * (/login), so these adapters get a private home under ~/.nexus/homes/<id>.
 * Persistent so the adapter keeps its own session/history; auth is injected via
 * env and is never sourced from this home.
 */
export function prepareThirdPartyClaudeHome(
  adapterId: string,
  cwd?: string,
): string {
  // Containment: the id becomes a path segment; reject traversal from a
  // hand-authored plugin adapter id.
  if (
    !adapterId ||
    adapterId.includes('..') ||
    adapterId.includes('/') ||
    adapterId.includes('\\') ||
    adapterId.includes('\0')
  ) {
    throw new Error(`invalid adapter id for isolated home: ${adapterId}`);
  }
  const dir = path.join(os.homedir(), '.nexus', 'homes', adapterId);
  fs.mkdirSync(path.join(dir, '.claude'), { recursive: true, mode: 0o700 });
  const onboardingMarker = path.join(dir, '.claude.json');
  let profile: Record<string, unknown> = { hasCompletedOnboarding: true };
  if (fs.existsSync(onboardingMarker)) {
    try {
      const parsed = JSON.parse(fs.readFileSync(onboardingMarker, 'utf8'));
      if (parsed && typeof parsed === 'object' && !Array.isArray(parsed)) {
        profile = parsed as Record<string, unknown>;
      }
    } catch {
      // keep fallback
    }
  }
  profile.hasCompletedOnboarding = true;
  if (cwd) {
    const existingProjects = (profile.projects && typeof profile.projects === 'object' && !Array.isArray(profile.projects))
      ? (profile.projects as Record<string, unknown>)
      : {};
    const trust = exactProjectTrust(cwd);
    profile.projects = {
      ...existingProjects,
      ...((trust.projects as Record<string, unknown>) ?? {}),
    };
  }
  fs.writeFileSync(
    onboardingMarker,
    JSON.stringify(profile, null, 2),
    { mode: 0o600 },
  );
  return dir;
}

/**
 * Pre-seed trust for the current workspace in ~/.claude.json so native Claude
 * doesn't stop on the "Trust this folder?" prompt when opened from Nexus IDE.
 */
export function ensureNativeClaudeProjectTrust(
  realHome: string,
  cwd?: string,
): void {
  if (!cwd) return;
  const profilePath = path.join(realHome, '.claude.json');
  try {
    let profile: Record<string, unknown> = {};
    if (fs.existsSync(profilePath)) {
      const parsed = JSON.parse(fs.readFileSync(profilePath, 'utf8'));
      if (parsed && typeof parsed === 'object' && !Array.isArray(parsed)) {
        profile = parsed as Record<string, unknown>;
      }
    }
    const existingProjects = (profile.projects && typeof profile.projects === 'object' && !Array.isArray(profile.projects))
      ? (profile.projects as Record<string, unknown>)
      : {};
    const trust = exactProjectTrust(cwd);
    profile.projects = {
      ...existingProjects,
      ...((trust.projects as Record<string, unknown>) ?? {}),
    };
    fs.writeFileSync(profilePath, JSON.stringify(profile, null, 2), { mode: 0o600 });
  } catch {
    // Best effort — do not fail spawn if realHome/.claude.json is not writable
  }
}

/**
 * Write only the MCP config file (ungated agents keep the real HOME but still
 * get the embedded server wired in via --mcp-config).
 */
export function writeMcpConfigFile(tokenId: string, mcpConfig: object): string {
  const dir = path.join(os.homedir(), '.nexus', 'mcp-configs');
  fs.mkdirSync(dir, { recursive: true, mode: 0o700 });
  const file = path.join(dir, `${tokenId.slice(0, 12)}.json`);
  // Contains the bearer token — 0600 so it isn't world-readable.
  fs.writeFileSync(file, JSON.stringify(mcpConfig, null, 2), { mode: 0o600 });
  return file;
}

/** Remove per-session artifacts once the session dies (best effort). */
export function cleanupSessionArtifacts(tokenId: string): void {
  const short = tokenId.slice(0, 12);
  const overlay = path.join(os.homedir(), '.nexus', 'ephemeral', short);
  try {
    // Resgata um /login fresco feito dentro do pane antes do rm — apenas para
    // overlays que carregaram a identidade NATIVA (marcador presente).
    if (fs.existsSync(path.join(overlay, CLAUDE_AUTH_SYNCBACK_MARKER))) {
      syncBackClaudeEphemeralAuth(overlay, os.homedir());
    }
  } catch {
    // Best effort only.
  }
  for (const target of [
    overlay,
    path.join(os.homedir(), '.nexus', 'mcp-configs', `${short}.json`),
    path.join(os.homedir(), '.nexus', 'mcp-configs', `${short}.settings.json`),
  ]) {
    try {
      fs.rmSync(target, { recursive: true, force: true });
    } catch {
      // Best effort only.
    }
  }
}
