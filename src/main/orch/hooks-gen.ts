/**
 * Create an isolated $HOME for a gated worker: hook settings, minimal
 * onboarding marker, and the MCP server config file. Returns the paths the
 * spawn decoration needs. O Keychain (macOS) guarda apenas o SEGREDO OAuth —
 * a IDENTIDADE de login é file-backed em ~/.claude.json, então o adapter
 * nativo precisa de carryNativeClaudeAuth para não cair em /login no pane.
 */
export function prepareEphemeralHome(
  tokenId: string,
  mcpConfig: object,
  options: EphemeralHomeOptions = {},
): EphemeralHome {
  const carryNativeClaudeAuth = options.carryNativeClaudeAuth === true && !options.managedClaudeAuthDir;
  const dir = path.join(
    os.homedir(),
    '.nexus',
    'ephemeral',
    tokenId.slice(0, 12),
  );
  // 0700: the ephemeral home holds the MCP bearer token — no other user on a
  // shared machine may read it (a leaked token grants the full toolset →
  // shell-pane spawn = RCE).
  fs.mkdirSync(dir, { recursive: true, mode: 0o700 });
  const claudeDir = path.join(dir, '.claude');
  fs.mkdirSync(claudeDir, { recursive: true, mode: 0o700 });
  // ponytail: reuse the per-pane config/auth HOME and link only conversations;
  // teardown needs no transcript migration or copy-back to the native profile.
  const providerSessionHome = options.checkoutId !== undefined
    ? linkProviderSessionState(
        options.adapterId ?? 'claude',
        claudeDir,
        options,
        ['projects', 'todos', 'tasks', 'file-history', 'plans'],
        { 'history.jsonl': '' },
        'claude',
      )
    : undefined;
  const nativeProfile = options.inheritNativeProfile
    ? readJsonObject(path.join(os.homedir(), '.claude.json'))
    : {};
  const nativeSettings = options.inheritNativeProfile
    ? readJsonObject(path.join(os.homedir(), '.claude', 'settings.json'))
    : {};
  const providerProfileReadPaths: string[] = [];
  // User settings must not redirect the private HOME back to native conversations.
  if (nativeSettings.env) {
    const settingsEnv = { ...objectValue(nativeSettings.env) };
    for (const key of ['HOME', 'USERPROFILE', 'CLAUDE_CONFIG_DIR', 'CLAUDE_SECURESTORAGE_CONFIG_DIR']) delete settingsEnv[key];
    if (options.managedClaudeAuthDir) {
      for (const key of ['CLAUDE_CODE_OAUTH_TOKEN', 'CLAUDE_CODE_OAUTH_REFRESH_TOKEN', 'CLAUDE_CODE_OAUTH_SCOPES', 'ANTHROPIC_API_KEY', 'ANTHROPIC_AUTH_TOKEN']) delete settingsEnv[key];
    }
    nativeSettings.env = settingsEnv;
  }
  if (options.inheritNativeProfile) {
    // Explicit executable/profile entries only: never projects, history or session indexes.
    // F-1157: sem filtro de skill — o diretório nativo de skills vem sempre.
    const entries = new Set(['skills', 'commands', 'agents', 'plugins', 'hooks', 'CLAUDE.md']);
    const nativeDir = path.join(os.homedir(), '.claude');
    linkSelectedEntries(nativeDir, claudeDir, entries);
    for (const name of entries) {
      const source = path.join(nativeDir, name);
      if (fs.existsSync(source)) providerProfileReadPaths.push(fs.realpathSync(source));
    }
  }

  const scriptPath = path.join(dir, 'nexus-gate.mjs');
  fs.writeFileSync(scriptPath, HOOK_SCRIPT, { mode: 0o700 });

  // System default: zero-click full-auto acknowledgement (Claude/GLM/Longcat).
  // The only Nexus entry below is the handoff spool hook (F-1154); it never
  // blocks a tool. mergeClaudeStatusHooks only APPENDS the additive status
  // hooks (emdash wave 1: UserPromptSubmit/Notification/Stop → /hook/status),
  // marker-separated and never touching the spool entry.
  // enabledPlugins:{} is an empty override map — mission panes must not inherit
  // the operator's plugin roster through the ephemeral overlay.
  // F-1157: sem `skillOverrides` — nenhuma skill é escondida do agente.
  const settings = {
    ...CLAUDE_FAMILY_ZERO_CLICK_SETTINGS,
    enabledPlugins: Object.freeze({}),
    // F-1154: sem hook Node de controle do Nexus em toda ferramenta (os de
    // status, `sh`+`curl`, seguem leves). O gate antigo custava um
    // processo Node antes e depois de cada chamada (e ~3 s com a admissão de
    // carga herdada) para decidir uma allowlist que a doutrina aboliu; o Stop
    // e o PostToolUse do gate não tinham efeito no Main.
    hooks: mergeClaudeStatusHooks({
      PreToolUse: [
        {
          matcher: NEXUS_HANDOFF_SUBMIT_HOOK_MATCHER,
          hooks: [
            { type: 'command', command: hookCommand(scriptPath, 'pretool') },
          ],
        },
      ],
    }),
  };
  fs.writeFileSync(
    path.join(claudeDir, 'settings.json'),
    JSON.stringify(options.gateHooks === false ? nativeSettings : settings, null, 2),
    { mode: 0o600 },
  );
  // Skip the first-run onboarding flow inside the ephemeral home. Para o
  // adapter Claude NATIVO, a identidade da conta viaja junto: o CLI decide
  // "logado" pelo oauthAccount de ~/.claude.json — o segredo do Keychain
  // sozinho não basta, então um stub vazio força /login com a máquina
  // autenticada. Third-party family (GLM/LongCat) nunca recebe a identidade.
  const nativeAuth = carryNativeClaudeAuth
    ? readNativeClaudeAuthIdentity(os.homedir())
    : {};
  // Uma missão main-owned, selada e já aprovada pode projetar trust para o cwd
  // exato dentro deste overlay descartável. Nos demais fluxos, carregamos apenas
  // uma decisão que já existia no perfil real; o helper nunca amplia confiança
  // por padrão e nunca escreve o ~/.claude.json real.
  const projectTrust =
    options.approvedMissionProjectTrust || options.workspaceProjectTrust
    ? exactProjectTrust(options.cwd)
    : readNativeProjectTrust(os.homedir(), options.cwd);
  // Fail-closed against official marketplace auto-install inside the disposable
  // HOME. A cold Claude pane used to clone claude-plugins-official during the
  // first idle→busy window; that busy/output edge looked like a turn start to
  // PTY diagnostics while UserPromptSubmit never fired, so kickoff timed out
  // and technical recovery spawned a second orchestrator PTY.
  fs.writeFileSync(
    path.join(dir, '.claude.json'),
    JSON.stringify({
      hasCompletedOnboarding: true,
      ...nativeAuth,
      ...(options.inheritNativeProfile && nativeProfile.mcpServers
        ? {
            mcpServers: projectMcpServersThroughHub(
              nativeProfile.mcpServers,
              tokenId,
              options.mcpHubBridge,
            ),
          }
        : {}),
      ...projectTrust,
      autoUpdates: false,
      officialMarketplaceAutoInstallAttempted: true,
      officialMarketplaceAutoInstalled: false,
      officialMarketplaceAutoInstallFailReason: 'policy_blocked',
      ...privateRuntimeClaudeKeyResponse(dir, options),
    }),
    { mode: 0o600 },
  );
  if (carryNativeClaudeAuth) {
    // Linux/Windows mantêm o segredo OAuth em arquivo; symlink faz o refresh
    // de token dentro do pane escrever direto no perfil real.
    const realCredentials = path.join(
      os.homedir(),
      '.claude',
      '.credentials.json',
    );
    if (!options.nativeCredentialsInPlace && fs.existsSync(realCredentials)) {
      const overlayCredentials = path.join(claudeDir, '.credentials.json');
      try {
        fs.rmSync(overlayCredentials, { force: true });
        linkFile(realCredentials, overlayCredentials);
      } catch {
        try {
          fs.copyFileSync(realCredentials, overlayCredentials);
          fs.chmodSync(overlayCredentials, 0o600);
        } catch {
          // Best effort — no macOS o segredo vive no Keychain.
        }
      }
    }
    // macOS: o segredo OAuth vive na login keychain, que o SO resolve como
    // ~/Library/Keychains/*.keychain-db relativo ao $HOME do PROCESSO. Num
    // HOME efêmero ela sai da lista de busca — o CLI abre "Not logged in" e
    // um /login gravaria num keychain descartável que morre com o overlay (o
    // login nunca "segura"). Linkar os keychain-db reais devolve a linhagem
    // do HOME real: leitura e escrita atravessam o link, então o refresh é
    // compartilhado com o perfil nativo e o /login persiste de verdade.
    fs.writeFileSync(path.join(dir, CLAUDE_AUTH_SYNCBACK_MARKER), '1', {
      mode: 0o600,
    });
  }

  // F-575/F-629: keychain real no overlay para o Claude PRIMEIRO-PARTE não
  // gated — conta nativa E conta gerenciada. Sem o link, toda escrita de
  // keychain no pane (refresh do próprio Claude, gh migrando token, git
  // osxkeychain, SDKs de terceiros) cai em "Chaves Não Encontradas", o modal
  // do macOS cujo botão "Reajustar Para Padrões" apaga o keychain do
  // operador. Conta gerenciada é segura: com CLAUDE_SECURESTORAGE_CONFIG_DIR
  // o CLI (2.1.280, verificado no binário) usa só o serviço
  // `Claude Code-credentials-<sha256(dir)[:8]>` — o mesmo de
  // managedClaudeKeychainService — e nunca lê o item nativo. Panes gated
  // recebem token por env (superfície mínima); terceiros (GLM/LongCat) nunca
  // recebem o link.
  const firstPartyClaudeAuth =
    carryNativeClaudeAuth || Boolean(options.managedClaudeAuthDir);
  if (
    firstPartyClaudeAuth &&
    process.platform === 'darwin' &&
    options.gateHooks === false
  ) {
    linkDarwinUserKeychains(os.homedir(), dir);
  }

  // Contains the bearer token — 0600.
  const mcpConfigPath = path.join(dir, 'nexus-mcp.json');
  fs.writeFileSync(mcpConfigPath, JSON.stringify(mcpConfig, null, 2), {
    mode: 0o600,
  });
  // F-579: projeta a identidade do operador depois que .claude/, .claude.json,
  // nexus-gate.mjs, keychains e o marcador de syncback já existem — o tier 2
  // nunca sobrescreve o estado privado do overlay (idempotente por entrada).
  if (options.carryNativeHome) linkNativeHomeEntries(os.homedir(), dir);
  if (options.carryDeveloperIdentity) linkDeveloperIdentity(os.homedir(), dir);
  return {
    dir,
    mcpConfigPath,
    ...(providerSessionHome ? { providerSessionHome } : {}),
    ...(providerProfileReadPaths.length ? { providerProfileReadPaths } : {}),
  };
}

/**
 * Pre-seed trust for the current workspace in ~/.claude.json so native Claude
 * doesn't stop on the "Trust this folder?" prompt when opened from Nexus IDE.
 */
export function ensureNativeClaudeProjectTrust(
  realHome: string,
  cwd?: string,
): void {
  if (!cwd) return;
  const profilePath = path.join(realHome, '.claude.json');
  try {
    let profile: Record<string, unknown> = {};
    if (fs.existsSync(profilePath)) {
      const parsed = JSON.parse(fs.readFileSync(profilePath, 'utf8'));
      if (parsed && typeof parsed === 'object' && !Array.isArray(parsed)) {
        profile = parsed as Record<string, unknown>;
      }
    }
    const existingProjects = (profile.projects && typeof profile.projects === 'object' && !Array.isArray(profile.projects))
      ? (profile.projects as Record<string, unknown>)
      : {};
    const trust = exactProjectTrust(cwd);
    profile.projects = {
      ...existingProjects,
      ...((trust.projects as Record<string, unknown>) ?? {}),
    };
    fs.writeFileSync(profilePath, JSON.stringify(profile, null, 2), { mode: 0o600 });
    clearClaudeConfigSnapshotCache();
  } catch {
    // Best effort — do not fail spawn if realHome/.claude.json is not writable
  }
}

/**
 * Write only the MCP config file (ungated agents keep the real HOME but still
 * get the embedded server wired in via --mcp-config).
 */
export function writeMcpConfigFile(tokenId: string, mcpConfig: object): string {
  const dir = path.join(os.homedir(), '.nexus', 'mcp-configs');
  fs.mkdirSync(dir, { recursive: true, mode: 0o700 });
  const file = path.join(dir, `${tokenId.slice(0, 12)}.json`);
  // Contains the bearer token — 0600 so it isn't world-readable.
  fs.writeFileSync(file, JSON.stringify(mcpConfig, null, 2), { mode: 0o600 });
  return file;
}

/** Remove per-session artifacts once the session dies (best effort). */
export function cleanupSessionArtifacts(tokenId: string): void {
  try { cleanupHeavyZshProfile(tokenId); } catch { /* best-effort physical-session cleanup */ }
  const short = tokenId.slice(0, 12);
  const overlay = path.join(os.homedir(), '.nexus', 'ephemeral', short);
  try {
    // Resgata um /login fresco feito dentro do pane antes do rm — apenas para
    // overlays que carregaram a identidade NATIVA (marcador presente).
    if (fs.existsSync(path.join(overlay, CLAUDE_AUTH_SYNCBACK_MARKER))) {
      syncBackClaudeEphemeralAuth(overlay, os.homedir());
    }
  } catch {
    // Best effort only.
  }
  for (const target of [
    overlay,
    path.join(os.homedir(), '.nexus', 'mcp-configs', `${short}.json`),
    path.join(os.homedir(), '.nexus', 'mcp-configs', `${short}.settings.json`),
  ]) {
    try {
      removeTreeSync(target, { recursive: true, force: true });
    } catch {
      // Best effort only.
    }
  }
}
