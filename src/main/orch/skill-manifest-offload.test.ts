import { createHash } from 'node:crypto';
import { describe, expect, it } from 'vitest';
import { offloadSkillManifest } from './skill-manifest-offload';

function generated(constName: string, manifest: Record<string, unknown>): string {
  return `// Auto-generated by scripts/bundle-skills.mjs. Do not edit manually.
export interface SkillAsset {
  content: string;
  encoding: 'utf8' | 'base64';
  /** Vendored executables (e.g. the impeccable CLI) must land runnable. */
  executable?: boolean;
}

export const ${constName}: Record<string, SkillAsset> = ${JSON.stringify(manifest, null, 2)};
`;
}

const sha256 = (bytes: Buffer): string => createHash('sha256').update(bytes).digest('hex');

const binary = Buffer.alloc(4096, 7);
const manifest = {
  'SKILL.md': { content: '# Skill\n', encoding: 'utf8' },
  'scripts/bin/cli': { content: binary.toString('base64'), encoding: 'base64', executable: true },
};
const options = {
  assetFileName: 'skills/demo-manifest.json',
  minContentLength: 1024,
  runtimeImport: './offloaded-skill-manifest',
};

describe('offloadSkillManifest', () => {
  it('moves large assets to the payload and keeps small ones inline', () => {
    const result = offloadSkillManifest(generated('DEMO_MANIFEST', manifest), options);
    expect(result).not.toBeNull();
    expect(JSON.parse(result!.asset)).toEqual({
      'scripts/bin/cli': manifest['scripts/bin/cli'].content,
    });
    expect(result!.code).toContain('export const DEMO_MANIFEST = offloadedSkillManifest(');
    expect(result!.code).toContain('"skills/demo-manifest.json"');
    expect(result!.code).toContain("from \"./offloaded-skill-manifest\"");
    expect(result!.code).toContain('# Skill');
    expect(result!.code).not.toContain(manifest['scripts/bin/cli'].content);
  });

  it('records the build-time digest and size of every asset', () => {
    const result = offloadSkillManifest(generated('DEMO_MANIFEST', manifest), options)!;
    expect(result.code).toContain(`"sha256":"${sha256(binary)}"`);
    expect(result.code).toContain(`"size":${binary.length}`);
    expect(result.code).toContain(`"sha256":"${sha256(Buffer.from('# Skill\n'))}"`);
    expect(result.code).toContain('"executable":true');
  });

  it('leaves manifests without large assets untouched', () => {
    const small = { 'SKILL.md': manifest['SKILL.md'] };
    expect(offloadSkillManifest(generated('SMALL_MANIFEST', small), options)).toBeNull();
  });

  it('only touches modules generated by bundle-skills', () => {
    expect(offloadSkillManifest('export const X = 1;\n', options)).toBeNull();
  });
});
